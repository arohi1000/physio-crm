#!/usr/bin/env node
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(repoRoot, process.env.OPENAPI_SPEC_PATH ?? "../physio-api/openapi.json");
const outputPath = resolve(repoRoot, "lib/api/generated/schema.ts");

if (!existsSync(specPath)) {
  console.error(
    [
      "",
      `Cannot generate API types: no OpenAPI spec at ${specPath}`,
      "",
      "The spec is produced by the physio-api repo. Either:",
      "  1. run the API's spec export so that file exists, or",
      "  2. point this script somewhere else:",
      "     OPENAPI_SPEC_PATH=/path/to/openapi.json npm run generate:api-types",
      "",
    ].join("\n"),
  );
  process.exit(1);
}

const ast = await openapiTS(pathToFileURL(specPath));

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `/* Generated by \`npm run generate:api-types\`. Do not edit by hand. */\n${astToString(ast)}`,
);

console.log(`Wrote ${outputPath}`);
